export function getLanguage() {
  const stored = localStorage.getItem(languageStorageKey);
  return supportedLanguages.includes(stored) ? stored : "es";
}
export function setStoredLanguage(language) { localStorage.setItem(languageStorageKey, supportedLanguages.includes(language) ? language : "es"); }
export function t(language, key) { return translations[language]?.[key] ?? translations.es[key] ?? key; }
